/**
 * Intelligent helper to fetch a translated string by key with fallbacks
 */
export function getTranslation(key: string, lang: string = "en", fallback?: string): string {
  const normalizedLang = lang.toLowerCase().split("-")[0]; // e.g. "ta-IN" -> "ta"
  
  if (translations[normalizedLang] && translations[normalizedLang][key]) {
    return translations[normalizedLang][key];
  }
  
  if (translations["en"] && translations["en"][key]) {
    return translations["en"][key];
  }

  return fallback || key;
}
